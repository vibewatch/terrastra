// All descriptions below are original text written for Terrastra. Chinese text lives in catalogue-zh.ts.
type N2 = [en: string, zh: string];
const n = ([en, zh]: N2) => ({ en, zh });
const desc = (key: string, en: string) => ({ en, zh: ZH[key]?.d });
const fun = (key: string, en: string) => ({ en, zh: ZH[key]?.f });

function L(key: string, slug: string, names: N2, country: string, continent: Continent, lat: number, lon: number,
  tier: 1 | 2 | 3, emoji: string, sub: string, model: ModelRecipe, facts: Facts, en: string, funEn: string, area = 0): CatalogueItem {
  return { key, slug, type: 'landmark', name: n(names), country, continent, lat, lon, tier, emoji, sub, model, facts,
    desc: desc(key, en), funFact: fun(key, funEn), area };
}

function A(key: string, slug: string, names: N2, country: string | undefined, continent: Continent | 'ocean', lat: number, lon: number,
  tier: 1 | 2 | 3, emoji: string, sub: string, model: ModelRecipe, facts: Facts,
  diet: 'carnivore' | 'herbivore' | 'omnivore', status: CatalogueItem['status'], habitat: string,
  en: string, funEn: string): CatalogueItem {
  return { key, slug, type: 'animal', name: n(names), country, continent, lat, lon, tier, emoji, sub, model, facts, diet, status,
    habitat: { en: habitat, zh: ZH[key]?.h }, desc: desc(key, en), funFact: fun(key, funEn) };
}

function D(key: string, slug: string, names: N2, continent: Continent | 'ocean', lat: number, lon: number, emoji: string,
  sub: string, model: ModelRecipe, facts: Facts, en: string, funEn: string, country?: string): CatalogueItem {
  return { key, slug, type: 'discovery', name: n(names), country, continent, lat, lon, tier: 2, emoji, sub, model, facts,
    desc: desc(key, en), funFact: fun(key, funEn) };
}

function V(key: string, slug: string, names: N2, emoji: string, route: Route, model: ModelRecipe, en: string, facts?: Facts, how?: N2): CatalogueItem {
  const [lat, lon] = route.pts[0];
  return { key, slug, type: 'vehicle', name: n(names), continent: 'ocean', lat, lon, tier: 1, emoji, sub: route.kind, model,
    desc: desc(key, en), route, ...(facts ? { facts } : {}), ...(how ? { how: n(how) } : {}) };
}

