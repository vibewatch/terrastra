/** Scales from the largest to the planets (the order of the scale ladder). */
export type ScaleId = 'universe' | 'laniakea' | 'group' | 'galaxy' | 'stars' | 'solar';
export type DeepScale = Exclude<ScaleId, 'solar'>;
export const SCALES: ScaleId[] = ['universe', 'laniakea', 'group', 'galaxy', 'stars', 'solar'];

export type DeepKind =
  | 'blackhole' | 'arm' | 'bar' | 'nebula' | 'remnant' | 'starcluster' | 'globular' | 'star'
  | 'galaxy' | 'dwarf' | 'group' | 'cluster' | 'supercluster' | 'region' | 'wall' | 'void' | 'quasar' | 'cmb' | 'deepfield';

export type Morph = 'spiral' | 'barred' | 'elliptical' | 'lenticular' | 'irregular' | 'dwarf';

export interface ScaleInfo {
  id: ScaleId;
  name: I18n;
  emoji: string;
  /** Rough diameter in light-years (for the card). */
  sizeLy: number;
  desc: I18n;
  funFact?: I18n;
  wiki: string;
}

export interface DeepObject {
  /** `dp_<slug>` (lower-case ASCII, unique). */
  key: string;
  scale: DeepScale;
  kind: DeepKind;
  name: I18n;
  emoji: string;
  /** Galactic longitude / latitude (deg) as seen from the Sun. */
  l: number;
  b: number;
  /** Distance from the Sun in light-years. */
  distLy: number;
  /** Rough diameter in light-years. */
  sizeLy?: number;
  /** Galaxies: shape, for the drawn sprite. */
  morph?: Morph;
  /** Bigger = drawn larger / labelled earlier (1 = normal, 3 = landmark). */
  rank?: number;
  /** Stars: spectral type of the (main) star, e.g. `M5.5V`, `K1.5III`, `DZ8`. */
  spec?: string;
  /** Number in Messier's catalogue (M1–M110), if it has one. */
  messier?: number;
  desc: I18n;
  funFact?: I18n;
  wiki: string;
}


