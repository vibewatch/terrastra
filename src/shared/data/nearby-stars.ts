/** Rough look of a star from its spectral type: colour class and kind of star (for the card). */
export type StarClass = 'red_dwarf' | 'orange_dwarf' | 'yellow_dwarf' | 'white_star' | 'blue_star' | 'giant' | 'white_dwarf' | 'brown_dwarf';
export function starClass(spec: string): StarClass {
  const c = spec[0];
  if (c === 'D') return 'white_dwarf';
  if (c === 'L' || c === 'T' || c === 'Y') return 'brown_dwarf';
  if (/I/.test(spec.slice(1).replace(/IV$/, ''))) return 'giant';
  return c === 'M' ? 'red_dwarf' : c === 'K' ? 'orange_dwarf' : c === 'G' ? 'yellow_dwarf' : c === 'O' || c === 'B' ? 'blue_star' : 'white_star';
}
/** Approximate colour (sRGB hex) of a star of spectral type `spec`. */
export function starColor(spec: string): string {
  const c = spec[0];
  return ({ O: '#9bb0ff', B: '#aabfff', A: '#cad7ff', F: '#f8f7ff', G: '#fff1d8', K: '#ffcf9a', M: '#ffad66', L: '#d9805a', T: '#c06b5a', D: '#e4ecff' } as Record<string, string>)[c] ?? '#ffffff';
}
