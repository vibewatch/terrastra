/**
 * Offline physical-geography gazetteer for school geography curricula (world & China):
 * continents, oceans, seas & gulfs, trenches & rifts, straits & canals, mountain ranges,
 * plateaus, plains, basins, deserts, major rivers & lakes, peninsulas, islands, and key lines.
 */

export type GeoKind =
  | 'continent'
  | 'ocean'
  | 'sea'
  | 'trench'
  | 'strait'
  | 'canal'
  | 'mountain'
  | 'plateau'
  | 'plain'
  | 'basin'
  | 'desert'
  | 'rift'
  | 'river'
  | 'lake'
  | 'peninsula'
  | 'island'
  | 'line';

export interface GazetteerEntry {
  key: `geo:${string}`;
  kind: GeoKind;
  emoji: string;
  name: { en: string; zh: string };
  aliases?: string[];
  region: { en: string; zh: string };
  lat: number;
  lon: number;
  /** Camera altitude in globe radii (`DEFAULT_H = 2.2`). */
  h: number;
  /** Minimum globe zoom (`×4.0` at `DEFAULT_H`) at which the surface label appears (`0` = already drawn by another layer). */
  labelZoom: number;
  desc: { en: string; zh: string };
  fact?: { en: string; zh: string };
  wiki?: [string, string];
}

const G = (
  slug: string,
  kind: GeoKind,
  emoji: string,
  name: [string, string],
  region: [string, string],
  lat: number,
  lon: number,
  h: number,
  labelZoom: number,
  desc: [string, string],
  opts: { aliases?: string[]; fact?: [string, string]; wiki?: [string, string] } = {},
): GazetteerEntry => ({
  key: `geo:${slug}`,
  kind,
  emoji,
  name: { en: name[0], zh: name[1] },
  region: { en: region[0], zh: region[1] },
  lat,
  lon,
  h,
  labelZoom,
  desc: { en: desc[0], zh: desc[1] },
  aliases: opts.aliases,
  fact: opts.fact ? { en: opts.fact[0], zh: opts.fact[1] } : undefined,
  wiki: opts.wiki,
});

